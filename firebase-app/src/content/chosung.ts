const INITIALS = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ';

/** "홈런" → "ㅎ ㄹ" (한글이 아니면 그대로) */
export function chosung(word: string): string {
  return [...word]
    .map((char) => {
      const code = char.charCodeAt(0) - 0xac00;
      return code >= 0 && code < 11172 ? INITIALS[Math.floor(code / 588)]! : char;
    })
    .join(' ');
}

export interface ChosungRound {
  initials: string;
  hint: string;
  answer: string;
  options: string[];
}

/** 한 판: 정답 하나 + 초성이 다른 보기 둘(섞음) */
export function chosungRound(random: () => number): ChosungRound {
  const [answer, hint] = CHOSUNG_TERMS[Math.floor(random() * CHOSUNG_TERMS.length)]!;
  const initials = chosung(answer);
  const others: string[] = [];
  const pool = CHOSUNG_TERMS.filter(([term]) => term !== answer && chosung(term) !== initials);
  while (others.length < 2 && pool.length > 0) {
    const [term] = pool.splice(Math.floor(random() * pool.length), 1)[0]!;
    others.push(term);
  }
  const options = [answer, ...others];
  for (let i = options.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [options[i], options[j]] = [options[j]!, options[i]!];
  }
  return { initials, hint, answer, options };
}
